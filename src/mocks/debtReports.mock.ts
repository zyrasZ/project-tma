const pad = (n: number) => n.toString().padStart(2, '0');

export const getRelativeDate = (daysAgo: number, timeStr = '10:30'): string => {
  const d = new Date();
  d.setDate(d.getDate() - daysAgo);
  return `${pad(d.getDate())}/${pad(d.getMonth() + 1)}/${d.getFullYear()} ${timeStr}`;
};

